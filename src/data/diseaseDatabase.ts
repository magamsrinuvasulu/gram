export function getDiseasesByCategory(categoryId: string): DiseaseInfo[] {
  if (categoryId === 'all') return SAMPLE_DISEASES;
  return SAMPLE_DISEASES.filter((d) => d.categoryId === categoryId);
}

export function searchDiseases(query: string, categoryId = 'all'): DiseaseInfo[] {
  const cleanQ = query.toLowerCase().trim();
  let list = SAMPLE_DISEASES;
  if (categoryId !== 'all') {
    list = list.filter((d) => d.categoryId === categoryId);
  }

  if (!cleanQ) return list;

  return list.filter((d) => {
    const combined = `${d.nameEn} ${d.nameTe} ${d.nameHi} ${d.definitionEn} ${d.definitionTe} ${d.definitionHi}`.toLowerCase();
    return combined.includes(cleanQ);
  });
}
